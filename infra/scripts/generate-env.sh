PGPASS_LANGFUSE=__RAND_HEX_16__
PGPASS_VERISETTLE_LEDGER=__RAND_HEX_16__
PGPASS_VERISETTLE_BACKEND=__RAND_HEX_16__

# MinIO root account
MINIO_ROOT_USER=verisettle_admin___RAND_HEX_4__
MINIO_ROOT_PASSWORD=__RAND_HEX_16__

# ----------------------------------------------------------------------
# 3. Identity governance
# ----------------------------------------------------------------------
# Keycloak admin console
KEYCLOAK_ADMIN=admin
