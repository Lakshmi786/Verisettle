#
# Generated by infra/scripts/generate-env.sh (make env). Never commit this
# file: it is gitignored, and it holds this machine's real credentials.
#
# Values marked [AUTO-FILLED] are written later by a setup script - the
# README says which one, at the step that produces them. Leave them blank.

# ----------------------------------------------------------------------
# 1. YOU MUST FILL THESE IN - the only two real external keys
# ----------------------------------------------------------------------
