KEYCLOAK_CONSOLE_CLIENT_SECRET=__RAND_HEX_16__

# Demo users seeded into the realm (ap.clerk.demo / controller.demo / cfo.demo)
DEMO_AP_CLERK_PASSWORD=__RAND_HEX_8__
