#!/bin/sh
# Writes .env for a local VeriSettle stack.
#
# The variable layout below IS the template - there is no .env.example in
# this repo, deliberately: a checked-in env file is the single most common
# way real credentials reach a public repo by accident, and a template that
# only ever holds placeholders still has to be kept in sync by hand. One
# script that emits the file removes both problems.
#
# Every __RAND_HEX_n__ below is replaced with a fresh `openssl rand -hex n`.
# The widths are not arbitrary - see docs/secrets-reference.md for why each
# value is 8, 12, 16 or 32 bytes.
#
# Refuses to overwrite an existing .env: once the stack has run, those
# secrets are baked into the Postgres, MinIO, Keycloak and Langfuse
# volumes, and regenerating them locks you out of your own data. To start
# genuinely fresh: make clean, then FORCE=1 make env.
#
# Run from the repo root: sh infra/scripts/generate-env.sh
set -eu

cd "$(dirname "$0")/../.."

if [ -f .env ] && [ "${FORCE:-0}" != "1" ]; then
  echo ".env already exists - refusing to overwrite it." >&2
  echo "Its secrets are baked into your Docker volumes; replacing them would" >&2
  echo "break the stack. To regenerate anyway: make clean && FORCE=1 make env" >&2
  exit 1
fi

TMPL=$(mktemp); OUT=$(mktemp)
trap 'rm -f "$TMPL" "$OUT"' EXIT

cat > "$TMPL" <<'EOT'
